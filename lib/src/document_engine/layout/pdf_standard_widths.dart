/// Larguras de avanço das fontes standard-14, em unidades de 1000/em.
///
/// **Por que este arquivo existe.** Quando o documento não traz faces
/// embutidas, o PDF desenha com as standard-14 (Helvetica/Times/Courier),
/// enquanto o COMPOSITOR mediu com as métricas do `FontRegistry` (Arial,
/// Times New Roman, Carlito…). As duas tabelas não coincidem — e, pior, o
/// registro não tem variante NEGRITO, então todo run em negrito era medido
/// com a largura do peso normal e desenhado ~4% mais largo. O run invadia o
/// seguinte: no ETP de referência a linha saía
/// "…gestão pública municipa[l], no modelo…" com as duas partes sobrepostas.
///
/// Com estas tabelas o renderer sabe, ANTES de escrever no content stream, a
/// largura exata que o leitor de PDF vai avançar, e absorve a diferença no
/// espaçamento entre caracteres (ver `pdf_renderer._standardFontFitPt`).
///
/// Os valores são os das AFM oficiais da Adobe para as 14 fontes-padrão
/// (Helvetica espaço=278, 'A'=667; Helvetica-Bold 'A'=722), extraídos com
/// PyMuPDF/`fitz.get_text_length` sobre o repertório WinAnsi que
/// `pdf_content.encodeWinAnsi` sabe codificar. São constantes públicas do
/// formato PDF, não dados de uma fonte de terceiros: nenhum binário de fonte
/// é distribuído por causa deste arquivo.
