/// O ajuste POR CARACTERE (`Tc`) que faz um run desenhado com [pdfFont] caber
/// exatamente na caixa que o compositor reservou ([targetWidthPt]).
///
/// Devolve 0 quando não há caixa, quando o texto não tem glifos, quando a
/// fonte não é uma standard-14 conhecida ou quando as duas pontas já
/// concordam — nesse último caso corrigir só poluiria o content stream.
///
/// Público (e separado do renderer) porque é aqui que mora a aritmética que
/// os testes precisam afirmar: o run desenhado tem de terminar onde a caixa
/// termina, senão ele invade o run seguinte.
double officeStandard14FitPerCharPt({
  required String text,
  required String pdfFont,
  required double sizePt,
  required double letterSpacingPt,
  required double wordSpacingPt,
  double? targetWidthPt,
}) {
  if (targetWidthPt == null || targetWidthPt <= 0) return 0;
  final count = text.runes.length;
  if (count == 0) return 0;
  final metrics = officeStandard14Widths[pdfFont];
  if (metrics == null) return 0;
  final natural = officeStandard14NaturalWidthPt(
    text: text,
    pdfFont: pdfFont,
    sizePt: sizePt,
    letterSpacingPt: letterSpacingPt,
    wordSpacingPt: wordSpacingPt,
  );
  if (natural <= 0) return 0;
  final delta = targetWidthPt - natural;
  // Um décimo de ponto no run inteiro não é diferença de fonte, é ruído de
  // arredondamento.
  if (delta.abs() < 0.1) return 0;
  // Guarda de sanidade: uma caixa absurdamente menor que o texto (métrica
  // exótica, glifo fora da tabela) não pode virar um amontoado ilegível.
  // Metade da largura natural é o piso.
  final floor = -natural / 2;
  return (delta < floor ? floor : delta) / count;
}

/// A largura que [pdfFont] vai realmente avançar ao desenhar [text].
double officeStandard14NaturalWidthPt({
  required String text,
  required String pdfFont,
  required double sizePt,
  double letterSpacingPt = 0,
  double wordSpacingPt = 0,
}) {
  final metrics = officeStandard14Widths[pdfFont];
  if (metrics == null) return 0;
  var spaces = 0;
  for (final rune in text.runes) {
    if (rune == 0x20) spaces++;
  }
  return metrics.measureWidth(text, sizePt) +
      letterSpacingPt * text.runes.length +
      wordSpacingPt * spaces;
}

